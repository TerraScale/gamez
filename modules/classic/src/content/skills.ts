/**
 * Skills (design §7.1 hero, §7.2 monster). Ranges are written in tiles and
 * converted with tiles(); durations are ticks. Hero skills are "classic.skill.*",
 * monster-only skills are "classic.mskill.*". `ai` hints drive the auto
 * controller (hero) and the monster AI.
 */
import { tiles } from "../fixed.ts";
import type { SkillProto } from "../types.ts";

const BASE: SkillProto = {
  name: "",
  description: "",
  icon: "",
  users: "hero",
  reqLevel: 1,
  maxRank: 20,
  shape: "melee",
  target: "enemy",
  range: 0,
  manaCost: 0,
  manaPerRank: 0,
  cooldown: 0,
  castTicks: 12,
  hitTick: 6,
  speedStat: "attack",
  weaponPct: 0,
  weaponPctPerRank: 0,
  damage: null,
  scaling: null,
  canMiss: false,
  effect: "",
  ai: { tags: ["single"], priority: 1 },
};

type Overrides = Partial<SkillProto> & Pick<SkillProto, "name" | "description">;

function skill(key: string, users: "hero" | "monster", p: Overrides): SkillProto {
  return { ...BASE, users, icon: `icon.skill.${key}`, effect: `fx.${key}`, ...p };
}

const hero = (key: string, p: Overrides): SkillProto => skill(key, "hero", p);
const mon = (key: string, p: Overrides): SkillProto => skill(key, "monster", p);

