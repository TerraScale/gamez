/**
 * Item bases (design §11.1): weapons, shields, helms, armour, gloves, boots,
 * rings, amulets and potions. Deeper tiers (ilvl up to 26) keep depth 16
 * supplied with bases. Weapon `range` is the basic-attack reach in sub
 * (melee ~1.6 tiles; bows and wands are ranged and fire `projectile`).
 */
import { tiles } from "../fixed.ts";
import type { EquipSlot, ItemBaseProto, ItemCategory, WeaponClass } from "../types.ts";

type Spec = Omit<ItemBaseProto, "icon" | "reqLevel" | "reqStr" | "reqDex" | "implicit"> &
  Partial<Pick<ItemBaseProto, "icon" | "reqLevel" | "reqStr" | "reqDex" | "implicit">>;

function iconOf(category: ItemCategory, weaponClass?: WeaponClass): string {
  return `icon.item.${weaponClass ?? category}`;
}

function item(p: Spec): ItemBaseProto {
  return {
    ...p,
    icon: p.icon ?? iconOf(p.category, p.weaponClass),
    reqLevel: p.reqLevel ?? p.ilvl,
    reqStr: p.reqStr ?? 0,
    reqDex: p.reqDex ?? 0,
    implicit: p.implicit ?? [],
  };
}

