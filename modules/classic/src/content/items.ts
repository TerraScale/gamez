function potion(
  name: string,
  tier: number,
  ilvl: number,
  value: number,
  dropWeight: number,
  kind: "life" | "mana" | "rejuv",
  amount: number,
  pct: number,
): ItemBaseProto {
  return item({
    name,
    category: "potion",
    slots: [],
    size: { w: 1, h: 1 },
    ilvl,
    value,
    dropWeight,
    potion: { kind, amount, pct, tier },
  });
}

