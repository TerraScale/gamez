/**
 * AccountDO (wave-B.md §3.3): the shared, cross-mode account — profile,
 * logins, sessions, wallet, universal stash, cosmetics, entitlements, block
 * list and guild slot. Name: the accountId.
 *
 * CONTRACT (architect-owned, frozen for builders): this class only adapts
 * storage and RPC to three logic classes, each owned by one task:
 *   account/profile.ts (T-auth), account/economy.ts (T-economy),
 *   account/social.ts (T-guilds).
 * Wave C (docs/design/wave-C.md §3) adds four more, each owned by one task:
 *   account/vault.ts + account/notices.ts (T-escrow; T-escrow also owns
 *   account/economy.ts in wave C), account/pass.ts (T-pass),
 *   account/purchases.ts (T-pay).
 * Need another RPC? Report it; do not edit this file.
 */
import type {
  AccountKind,
  AccountView,
  AuthProvider,
  CosmeticSlot,
  NoticeInput,
  PassTrack,
  PaymentProviderId,
  ProductPrice,
  UniversalItem,
  VaultItemInput,
} from "@gamez/protocol";
import { Outbox, type ReplicationBatch } from "@gamez/sync";
import { DurableObject } from "cloudflare:workers";
import { AccountActivityStore } from "../account/activity.ts";
import { AccountEconomy } from "../account/economy.ts";
import { AccountProfileStore } from "../account/profile.ts";
import { AccountSocial } from "../account/social.ts";
import { AccountNotices } from "../account/notices.ts";
import { AccountPass } from "../account/pass.ts";
import { AccountPurchases, type FulfillInput } from "../account/purchases.ts";
import { AccountVault, vaultFullNotice } from "../account/vault.ts";
import {
  sqlStoreOf,
  type AccountApi,
  type AccountApiC,
  type WalletTxC,
  type EntitlementGrant,
  type Env,
  type GuildMembership,
  type WalletTx,
  type VaultPutOptions,
} from "../contracts.ts";

const FLUSH_BATCH = 200;

export class AccountDO extends DurableObject<Env> implements AccountApi, AccountApiC {
  readonly #outbox: Outbox;
  readonly #profile: AccountProfileStore;
  readonly #activity: AccountActivityStore;
  readonly #economy: AccountEconomy;
  readonly #social: AccountSocial;
  readonly #vault: AccountVault;
  readonly #notices: AccountNotices;
  readonly #pass: AccountPass;
  readonly #purchases: AccountPurchases;

  constructor(ctx: DurableObjectState, env: Env) {
    super(ctx, env);
    const store = sqlStoreOf(ctx.storage);
    const accountId = ctx.id.name ?? ctx.id.toString();
    this.#outbox = new Outbox(ctx.storage.sql, `account:${accountId}`);
    this.#profile = new AccountProfileStore(store, accountId, this.#outbox);
    this.#activity = new AccountActivityStore(store, this.#profile, this.#outbox, accountId);
    this.#economy = new AccountEconomy(store);
    this.#social = new AccountSocial(store, Date.now, accountId);
    this.#vault = new AccountVault(store, this.#economy, this.#outbox, accountId);
    this.#notices = new AccountNotices(store);
    // A delivery the vault refused waits in custody: tell the player once per full spell.
    this.#vault.onWaitStarted = (txId) => {
      this.#notices.notify(vaultFullNotice(txId));
    };
    this.#pass = new AccountPass(
      store,
      this.#economy,
      this.#vault,
      this.#notices,
      Date.now,
      this.#outbox,
      accountId,
    );
    this.#purchases = new AccountPurchases(
      store,
      this.#economy,
      this.#vault,
      this.#notices,
      this.#outbox,
      accountId,
    );
    void ctx.blockConcurrencyWhile(async () => {
      this.#outbox.init();
      this.#profile.init();
      this.#activity.init();
      this.#economy.init();
      this.#social.init();
      this.#vault.init();
      this.#notices.init();
      this.#pass.init();
      this.#purchases.init();
    });
  }

  async #flushSoon(): Promise<void> {
    if (this.#outbox.size() > 0) await this.#outbox.scheduleFlush(this.ctx.storage);
  }

  async alarm(): Promise<void> {
    const sink = {
      send: async (batch: ReplicationBatch) => {
        await this.env.SYNC_QUEUE.send(batch);
      },
    };
    await this.#outbox.flush(sink, FLUSH_BATCH);
    if (this.#outbox.size() > 0) await this.#outbox.scheduleFlush(this.ctx.storage, 0);
  }

  // ---- profile and sessions (T-auth)
  async ensure(input: { kind: AccountKind; displayName: string }) {
    const p = this.#profile.ensure(input);
    await this.#flushSoon();
    return p;
  }
  async profile() {
    return this.#profile.profile();
  }
  async view(): Promise<AccountView | null> {
    const p = this.#profile.profile();
    if (!p) return null;
    const g = this.#social.guild();
    return {
      accountId: p.accountId,
      displayName: p.displayName,
      kind: p.kind,
      identities: p.identities.map((i) =>
        i.email !== null ? { provider: i.provider, email: i.email } : { provider: i.provider },
      ),
      guildId: g?.guildId ?? null,
      guildTag: g?.tag ?? null,
      createdAt: p.createdAt,
    };
  }
  async setDisplayName(name: string) {
    const p = this.#profile.setDisplayName(name);
    await this.#flushSoon();
    return p;
  }
  async addIdentity(identity: { provider: AuthProvider; subject: string; email: string | null }) {
    const p = this.#profile.addIdentity(identity);
    await this.#flushSoon();
    return p;
  }
  async openSession(userAgent: string) {
    return this.#profile.openSession(userAgent);
  }
  /** A valid session counts as activity (account/activity.ts, once per UTC day). */
  async checkSession(sid: string) {
    const ok = this.#activity.checkSession(sid, Date.now());
    if (ok) await this.#flushSoon();
    return ok;
  }
  async touchActivity(now: number): Promise<void> {
    this.#activity.touch(now);
    await this.#flushSoon();
  }

  async closeSession(sid: string) {
    this.#profile.closeSession(sid);
  }

  // ---- shared economy (T-economy)
  async wallet() {
    return this.#economy.wallet();
  }
  async applyWalletTx(tx: WalletTx) {
    // Wave C: the wallet change writes economy_ledger/account_wallet outbox rows.
    const r = this.#economy.applyWalletTx(tx);
    await this.#flushSoon();
    return r;
  }
  async stash() {
    return this.#economy.stash();
  }
  async stashAdd(txId: string, item: Omit<UniversalItem, "uid">) {
    const r = this.#economy.stashAdd(txId, item);
    await this.#flushSoon();
    return r;
  }
  async stashRemove(txId: string, uid: string, count: number) {
    const r = this.#economy.stashRemove(txId, uid, count);
    await this.#flushSoon();
    return r;
  }
  async cosmetics() {
    return this.#economy.cosmetics();
  }
  async equipCosmetic(slot: CosmeticSlot, id: string | null) {
    return this.#economy.equipCosmetic(slot, id);
  }
  async grantEntitlement(grant: EntitlementGrant) {
    const r = this.#economy.grantEntitlement(grant);
    this.#pass.syncProgress(); // a premium grant changes pass_progress (admin dashboard §6)
    await this.#flushSoon();
    return r;
  }
  async entitlements() {
    return this.#economy.entitlements();
  }

  // ---- social (T-guilds)
  async blocks() {
    return this.#social.blocks();
  }
  async setBlocked(target: string, blocked: boolean) {
    return this.#social.setBlocked(target, blocked);
  }
  async guild() {
    return this.#social.guild();
  }
  async reserveGuild(opId: string, guildId: string) {
    return this.#social.reserveGuild(opId, guildId);
  }
  async confirmGuild(opId: string, membership: GuildMembership) {
    this.#social.confirmGuild(opId, membership);
  }
  async releaseGuild(opId: string, guildId: string) {
    this.#social.releaseGuild(opId, guildId);
  }

  // ---- wave C: vault, wallet with telemetry, notices (T-escrow)
  async vault() {
    return this.#vault.vault();
  }
  async vaultGet(uid: string) {
    return this.#vault.vaultGet(uid);
  }
  async vaultPut(txId: string, item: VaultItemInput, opts?: VaultPutOptions) {
    const r = this.#vault.vaultPut(txId, item, opts);
    await this.#flushSoon();
    return r;
  }
  async vaultWaiting() {
    return this.#vault.waiting();
  }
  async vaultTake(txId: string, uid: string) {
    const r = this.#vault.vaultTake(txId, uid);
    await this.#flushSoon();
    return r;
  }
  async walletTx(tx: WalletTxC) {
    const r = this.#vault.walletTx(tx);
    await this.#flushSoon();
    return r;
  }
  async notify(notice: NoticeInput) {
    this.#notices.notify(notice);
    await this.#flushSoon();
  }
  async notices(sinceId: string | null) {
    return this.#notices.notices(sinceId);
  }
  async markNoticesRead(upToId: string) {
    return this.#notices.markRead(upToId);
  }
  async linkTrade(tradeId: string, open: boolean) {
    this.#notices.linkTrade(tradeId, open);
  }
  async openTrades() {
    return this.#notices.openTrades();
  }

  // ---- wave C: battle pass (T-pass)
  async seasonProgress(source: string, total: number) {
    const v = this.#pass.seasonProgress(source, total);
    await this.#flushSoon();
    return v;
  }
  async addSeasonXp(txId: string, xp: number, reason: string) {
    const v = this.#pass.addXp(txId, xp, reason);
    await this.#flushSoon();
    return v;
  }
  async pass() {
    return this.#pass.view();
  }
  async claimPassReward(tier: number, track: PassTrack) {
    const r = this.#pass.claim(tier, track);
    await this.#flushSoon();
    return r;
  }

  // ---- wave C: purchases (T-pay)
  async createOrder(input: {
    orderId: string;
    sku: string;
    provider: PaymentProviderId;
    price: ProductPrice;
  }) {
    const r = this.#purchases.createOrder(input);
    await this.#flushSoon();
    return r;
  }
  async fulfillOrder(input: FulfillInput) {
    const r = this.#purchases.fulfillOrder(input);
    this.#pass.syncProgress(); // a store grant may be the premium pass
    await this.#flushSoon();
    return r;
  }
  async refundOrder(input: { orderId: string; eventId: string }) {
    const r = this.#purchases.refundOrder(input);
    this.#pass.syncProgress(); // a refund revokes the premium grant
    await this.#flushSoon();
    return r;
  }
  async orders() {
    return this.#purchases.orders();
  }
}
